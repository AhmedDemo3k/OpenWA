import { ValidationPipe } from '@nestjs/common';
import { SwaggerModule, DocumentBuilder } from '@nestjs/swagger';
import type { NestExpressApplication } from '@nestjs/platform-express';
import helmet from 'helmet';
import { AppModule } from './app.module';
import { ShutdownService } from './common/services/shutdown.service';
import { resolveDashboardIndex } from './common/utils/dashboard-dist';
import * as dotenv from 'dotenv';
import * as fs from 'fs';
import * as path from 'path';

/**
 * Serves the built dashboard from this same process.
 *
 * The dashboard is a Vite SPA that calls `/api` with a relative path, so it only works when
 * it is served from the same origin as the API. Previously it ran as a second Vite dev
 * server on port 2886, which meant a second thing to start, a second port to map through
 * Tailscale Funnel, and a CORS exemption between them. None of that was set up on this
 * host, so the funnel URL resolved to the API, the API's landing page advertised a
 * dashboard port with nothing behind it, and following that link produced a blank page with
 * no way to enter an API key.
 *
 * One origin removes the whole class of problem. If `dashboard/dist` is absent the API still
 * boots and simply keeps serving the API-only landing page.
 */
function mountDashboard(app: NestExpressApplication): boolean {
  const indexFile = resolveDashboardIndex();

  if (!indexFile) {
    console.warn(
      '[Dashboard] No dashboard build found; serving API only. ' +
        'Run "npm --prefix dashboard run build" to enable it.',
    );
    return false;
  }

  const distDir = path.dirname(indexFile);

  // Serve the hashed assets first. Everything else that is not an /api route falls through
  // to index.html so client-side routes survive a refresh.
  app.useStaticAssets(distDir, { index: false, redirect: false });

  app.use((req: { path: string; url: string }, res: { sendFile: (p: string) => void }, next: () => void) => {
    if (req.path.startsWith('/api')) return next();
    if (req.path.includes('.')) return next(); // a missing asset is a real 404, not the SPA
    return res.sendFile(indexFile);
  });

  console.log(`[Dashboard] Serving dashboard build from ${distDir}`);
  return true;
}

/**
 * Waits until everything already written to a stdio stream has actually reached the OS.
 *
 * Writes to a pipe are asynchronous, and the pipes Docker attaches to stdout/stderr are
 * pipes. `process.exit()` does not wait for them, so a crash handler that logs and then
 * exits immediately can lose the very message explaining the crash — the container records
 * a non-zero exit code and nothing else.
 *
 * Writing an empty string is enough: its callback fires once the stream has drained
 * everything queued ahead of it.
 */
function flushStream(stream: NodeJS.WriteStream): Promise<void> {
  if (stream.writableLength === 0) {
    return Promise.resolve();
  }
  return new Promise<void>(resolve => {
    stream.write('', () => resolve());
  });
}

async function flushStdio(): Promise<void> {
  await Promise.all([flushStream(process.stdout), flushStream(process.stderr)]);
}

// Configuration loading order (later sources do NOT override earlier ones):
//   1. Process env (Docker, shell, systemd) — highest priority
//   2. .env (project-level overrides committed/managed by the user)
//   3. data/.env.generated (Dashboard-managed config; created on first run)
//
// Rationale: explicit env vars from the host/orchestrator must always win
// so that operators can override the Dashboard-saved config without having
// to edit data/.env.generated by hand.
const generatedEnvPath = path.resolve(process.cwd(), 'data', '.env.generated');
const userEnvPath = path.resolve(process.cwd(), '.env');

// Ensure data directory exists
const dataDir = path.dirname(generatedEnvPath);
if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}

// 2. User-managed .env (does not override real process env)
if (fs.existsSync(userEnvPath)) {
  console.log('[Bootstrap] Loading .env from:', userEnvPath);
  dotenv.config({ path: userEnvPath, override: false });
}

// 3. Dashboard-saved config (does not override .env or process env)
if (fs.existsSync(generatedEnvPath)) {
  console.log('[Bootstrap] Loading saved configuration from:', generatedEnvPath);
  dotenv.config({ path: generatedEnvPath, override: false });
} else {
  console.log('[Bootstrap] First run detected, creating default configuration...');
  // Create minimal .env.generated with sensible defaults
  const minimalConfig = `# OpenWA Configuration
# Generated automatically on first run
# Edit via Dashboard > Infrastructure or modify this file directly.
# Note: values in process env or project .env take precedence over this file.

# Database (SQLite - no external service required)
DATABASE_TYPE=sqlite
POSTGRES_BUILTIN=false

# Redis & Queue (disabled by default)
REDIS_ENABLED=false
REDIS_BUILTIN=false
QUEUE_ENABLED=false

# Storage (Local filesystem)
STORAGE_TYPE=local
MINIO_BUILTIN=false
STORAGE_PATH=./data/media

# Docker Profiles: none (minimal setup)
`;
  fs.writeFileSync(generatedEnvPath, minimalConfig);
  console.log('[Bootstrap] Created default configuration at:', generatedEnvPath);
  dotenv.config({ path: generatedEnvPath, override: false });
}

async function bootstrap() {
  const app = await NestFactory.create<NestExpressApplication>(AppModule);

  // Enable shutdown hooks for graceful shutdown
  app.enableShutdownHooks();

  // Wire up graceful shutdown service
  const shutdownService = app.get(ShutdownService);
  shutdownService.setShutdownCallback(async () => {
    await app.close();
  });

  // Last-resort process guards. Node's default for both of these is to terminate the
  // process, so a single stray rejection (a transient SQLITE_BUSY on a fire-and-forget
  // write, a plugin throwing inside an event handler) would otherwise take every WhatsApp
  // session offline. They log loudly and exit non-zero so the orchestrator can restart us
  // in a known-good state rather than leaving a half-broken process serving traffic.
  //
  // Registered only once `app` exists, because closing gracefully needs it. Anything that
  // fails earlier is handled by the `bootstrap().catch()` below.
  //
  // These deliberately do *not* call `process.exit(1)` directly. Two things go wrong then:
  //   - stdout/stderr are asynchronous when piped (which is exactly how Docker collects
  //     them), so the fatal error itself is dropped and `docker logs` shows nothing;
  //   - `app.close()` never runs, so Chromium is orphaned, SQLite never checkpoints its
  //     WAL, queued webhooks and in-flight sends are lost, and the process is SIGKILLed
  //     by the orchestrator's grace timer instead of stopping in a known state.
  const CRASH_SHUTDOWN_BUDGET_MS = 10_000;
  let shuttingDown = false;

  const exitAfterCrash = async (label: string, detail: unknown): Promise<void> => {
    // A second crash while we are already tearing down must not start a competing teardown.
    if (shuttingDown) return;
    shuttingDown = true;

    console.error(`[FATAL] ${label}:`, detail);
    if (detail instanceof Error && detail.stack) {
      console.error(detail.stack);
    }

    // After an uncaught exception the process state is undefined, so this must be bounded:
    // a wedged engine or a dead socket can make `app.close()` hang forever.
    const hardTimeout = setTimeout(() => {
      console.error('[FATAL] Graceful shutdown timed out; exiting immediately');
      process.exit(1);
    }, CRASH_SHUTDOWN_BUDGET_MS);
    // Do not let this timer alone keep the process alive if close() finishes first.
    hardTimeout.unref?.();

    try {
      await app.close();
      console.error('[FATAL] Graceful shutdown completed');
    } catch (closeError: unknown) {
      console.error('[FATAL] Error during shutdown:', closeError);
    }

    clearTimeout(hardTimeout);
    await flushStdio();
    process.exit(1);
  };

  process.on('unhandledRejection', (reason: unknown) => {
    void exitAfterCrash('Unhandled promise rejection', reason);
  });

  process.on('uncaughtException', (error: Error) => {
    void exitAfterCrash('Uncaught exception', error);
  });

  // Enhanced Security Headers (Phase 3 Security Audit)
  app.use(
    helmet({
      contentSecurityPolicy: {
        directives: {
          defaultSrc: ["'self'"],
          styleSrc: ["'self'", "'unsafe-inline'"],
          scriptSrc: ["'self'"],
          imgSrc: ["'self'", 'data:', 'https:'],
          connectSrc: ["'self'"],
          fontSrc: ["'self'"],
          objectSrc: ["'none'"],
          upgradeInsecureRequests: process.env.NODE_ENV === 'production' ? [] : null,
        },
      },
      hsts: {
        maxAge: 31536000,
        includeSubDomains: true,
        preload: true,
      },
      noSniff: true,
      referrerPolicy: { policy: 'strict-origin-when-cross-origin' },
      // Disable for API usage
      crossOriginResourcePolicy: { policy: 'cross-origin' },
    }),
  );

  // CORS Configuration (Phase 3 Security Audit)
  const allowedOrigins = process.env.CORS_ORIGINS?.split(',').map(o => o.trim()) || ['*'];
  app.enableCors({
    origin: (origin: string | undefined, callback: (err: Error | null, allow?: boolean) => void) => {
      // Allow requests with no origin (mobile apps, Postman, server-to-server)
      if (!origin) return callback(null, true);

      // Check if wildcard or origin matches
      if (allowedOrigins.includes('*') || allowedOrigins.includes(origin)) {
        callback(null, true);
      } else {
        callback(new Error('Not allowed by CORS'));
      }
    },
    credentials: true,
    methods: ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'OPTIONS'],
    allowedHeaders: ['Content-Type', 'X-API-Key', 'Authorization', 'X-Request-ID'],
    exposedHeaders: ['X-RateLimit-Limit', 'X-RateLimit-Remaining', 'X-RateLimit-Reset'],
    maxAge: 86400, // 24 hours
  });

  // Global prefix
  app.setGlobalPrefix('api', { exclude: ['/'] });

  // Enhanced Validation pipe with security options
  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true, // Strip properties not in DTO
      forbidNonWhitelisted: true, // Throw error on unknown properties
      transform: true,
      transformOptions: {
        enableImplicitConversion: true,
      },
      disableErrorMessages: process.env.NODE_ENV === 'production', // Hide details in prod
    }),
  );

  // Swagger documentation
  const config = new DocumentBuilder()
    .setTitle('OpenWA API')
    .setDescription('Open Source WhatsApp API Gateway - Free, Self-Hosted HTTP API')
    .setVersion('0.1.6')
    .addApiKey({ type: 'apiKey', name: 'X-API-Key', in: 'header' }, 'X-API-Key')
    .addTag('sessions', 'WhatsApp session management')
    .addTag('messages', 'Send and manage messages')
    .addTag('webhooks', 'Webhook configuration')
    .addTag('contacts', 'Contact management')
    .addTag('groups', 'Group management')
    .addTag('labels', 'Label management (WhatsApp Business)')
    .addTag('channels', 'Channel/Newsletter management')
    .addTag('health', 'Health check endpoints')
    .build();

  const document = SwaggerModule.createDocument(app, config);
  SwaggerModule.setup('api/docs', app, document);

  // Must come after the global prefix is set, so the /api guard below matches the real
  // route the Swagger middleware registered.
  const dashboardMounted = mountDashboard(app);

  const port = process.env.PORT || 2785;
  await app.listen(port);

  console.log(`🚀 OpenWA is running on: http://localhost:${port}`);
  console.log(`📚 Swagger docs: http://localhost:${port}/api/docs`);
  if (dashboardMounted) {
    console.log(`🖥️  Dashboard:   http://localhost:${port}/`);
  }
}

// A boot failure (EADDRINUSE, bad DATABASE_*, migration error) must not surface as a
// bare unhandled rejection: log it properly and exit non-zero so the supervisor reacts.
// There is no app to close at this point, but the log still has to survive the exit.
void bootstrap().catch(async (error: unknown) => {
  console.error('[FATAL] Failed to start OpenWA:', error);
  if (error instanceof Error && error.stack) {
    console.error(error.stack);
  }
  await flushStdio();
  process.exit(1);
});
